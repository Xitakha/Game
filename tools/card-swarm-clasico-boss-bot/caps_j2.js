const { chromium } = require('/opt/node-tools/node_modules/playwright');
const BOSS = process.argv[2] || 'karceron', PORT = process.argv[3] || 8765;
const OUT = '/home/user/Game/studio/docs/capturas-jefes-j2-logica/' + BOSS.slice(0, 1) + '_';
require('fs').mkdirSync('/home/user/Game/studio/docs/capturas-jefes-j2-logica/', { recursive: true });
async function runK() {
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--no-sandbox', '--autoplay-policy=no-user-gesture-required'] });
  const pg = await b.newPage({ viewport: { width: 960, height: 540 } });
  const errs = [];
  pg.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
  pg.on('pageerror', e => errs.push('PAGEERR ' + e.message + ' ' + (e.stack || '').split('\n').slice(1, 4).join('|')));
  await pg.goto('http://localhost:' + PORT + '/index.html?boss=' + BOSS + '&god=1&reset=1&hand=spark:3,dart:3,shard:2,dagger:2,fang:2&speed=1&hpcal=4');
  await pg.evaluate(() => { setInterval(() => { if (G.state === 'cards' && G.Cards.off) { try { G.Cards.off.mode === 'level' ? G.Cards.skip() : G.Cards.pick(0); } catch (e) { } } }, 100); });
  const shot = async (n) => { await pg.screenshot({ path: OUT + n + '.png' }); };
  const info = async () => console.log(JSON.stringify(await pg.evaluate(() => G.Boss.info())));
  await pg.waitForTimeout(400); await shot('01_intro_grietas');
  await pg.waitForTimeout(900); await shot('02_intro_surge');
  await pg.waitForTimeout(1100); await shot('03_intro_titulo');
  await pg.waitForTimeout(1000); await shot('04_intro_rugido');
  await pg.waitForTimeout(1800);
  await pg.evaluate(() => { G.god = true; });
  async function free() { for (let i = 0; i < 80; i++) { const r = await pg.evaluate(() => G.Boss.e && !G.Boss.e.atk && G.Boss.e.mode === 'fight' && G.Boss.e.stagT <= 0); if (r) return; await pg.waitForTimeout(150); } }
  const att = async (name, wait, n) => { await free(); await pg.evaluate((a) => { G.Boss.force(a); }, name); await pg.waitForTimeout(wait); await shot(n); };
  await att('k_martillo', 700, '05_martillo_tele');
  await pg.waitForTimeout(600); await shot('06_martillo_ventana');
  await att('k_grilletes', 750, '07_grilletes_tele');
  await att('k_brasas', 1400, '08_brasas_tele');
  await att('k_costillas', 500, '09_costillas_tele');
  await att('k_erupcion', 800, '10_erupcion_tele');
  await pg.waitForTimeout(1500); await shot('11_erupcion_pecho_abierto');
  await pg.waitForTimeout(3500);
  await pg.evaluate(() => { G.Boss.gate(); }); await pg.waitForTimeout(1200); await shot('12_fase2_gate');
  await pg.waitForTimeout(3500);
  await att('k_aliento', 850, '13_aliento_tele');
  await pg.waitForTimeout(900); await shot('14_aliento_barrido');
  await att('k_penitentes', 600, '15_penitentes');
  await pg.evaluate(() => { G.Boss.e.stagT = 0; G.Boss.e.atk = null; G.Boss.e.bst = 'idle'; G.Boss.gate(); }); await pg.waitForTimeout(1200); await shot('16_fase3_gate');
  await pg.waitForTimeout(3500);
  await att('k_marea', 1500, '17_marea_tele');
  await pg.waitForTimeout(1500); await shot('18_marea_activa');
  await pg.waitForTimeout(8000);
  await pg.evaluate(() => { G.Boss.breakKey('maza'); }); await pg.waitForTimeout(500); await shot('19_maza_rota');
  await pg.evaluate(() => { G.Boss.breakKey('grillete'); }); await pg.waitForTimeout(500); await shot('20_grillete_roto');
  await pg.evaluate(() => { G.Boss.breakKey('nucleo'); }); await pg.waitForTimeout(500); await shot('21_nucleo_roto');
  await info();
  await pg.evaluate(() => { const e = G.Boss.e; e.atk = null; e.bst = 'idle'; e.stagT = 0; e.hp = e.maxHp * 0.079; G.Boss.afterHit(e); e.immune = true; });
  await pg.waitForTimeout(1500); await shot('22_requiem_tele');
  await pg.waitForTimeout(3500); await shot('23_requiem_inundado');
  await pg.waitForTimeout(3000); await shot('24_requiem_islas');
  await info();
  await pg.evaluate(() => { G.Boss.e.immune = false; G.Combat.deal(G.Boss.e, 99999, { tag: 'ice', proj: true }); });
  await pg.waitForTimeout(600); await shot('25_muerte_a');
  await pg.waitForTimeout(1800); await shot('26_muerte_b');
  for (let i = 0; i < 40; i++) { await pg.waitForTimeout(250); if (await pg.evaluate(() => G.state === 'gameover')) break; }
  await pg.waitForTimeout(400); await shot('27_victoria');
  console.log(await pg.evaluate(() => JSON.stringify(G.Loot.summary && G.Loot.summary.boss)));
  console.log(JSON.stringify(await pg.evaluate(() => G.Boss.karceronCoverage())));
  console.log(errs.join('\n') || 'NO ERRORS');
  await b.close();
}
